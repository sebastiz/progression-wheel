/* band-templates — arrangement templates for the music that is played by a band rather than mixed
   by a DJ: pop, rock, metal, blues, soul, jazz, folk, country, Latin, reggae, hip-hop, film.

   Same shape as the dance catalogue in arrange-templates.js (`[id, name, tip, sound, rows]`, a row
   being `["Section|nums|reps|note", { what plays }]`) and merged into the same `DANCE_TEMPLATES`
   array, so everything that consumes a template — the structure picker, `applyArrangement`, the
   strip, `npm test`'s energy checks — takes these without knowing the difference.

   The difference is in what the rows say. A dance arrangement is made of *subtraction*: the drop
   lands because the breakdown took the kick away. A band arrangement is made of *re-voicing*: the
   verse is the same five people as the chorus with the guitar palm-muted, the drummer on the rim
   and the strings sat out, and the chorus is the fuzz pedal going on. So beside the on/off lanes
   these rows set, per section, the chord instrument and rhythm, the kit, the bass and perc
   patterns, the pad voice, and an insert rack — the fields `resolveArrangement` reads as
   `kit`, `chordInstr`, `chordPat`, `bassPat`, `bassVoice`, `percPat`, `percKit`, `padVoice`, `fx`.

   Every template is an *archetype* — the shape of a form, not of one genre — and carries a
   deliberately neutral sound bundle. The genre that points at it (genre-emotion-presets.js) lays
   its own instruments, tempo and groove over that bundle, so a Country song and a Folk song share
   the storyteller's running order and dynamics while sounding nothing alike. The one place a row
   names an instrument outright is where the *form* demands it: a rock verse is palm-muted whatever
   the genre's guitar is, a quiet/loud verse is clean whatever the chorus is.

   Bar maths as in the dance catalogue: LOOP is 4 bars a pass, HALF1/HALF2 and HOLD1 are 2 — every
   row here is a whole four-bar group. Section names stay inside `letterFor`'s vocabulary so the
   strip colours and letters them. */

